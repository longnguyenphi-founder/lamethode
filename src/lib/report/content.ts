// Generated by `npm run reports:build` from content-source/reports/ — do not edit by hand.

export type Block =
  | { type: "p"; text: string }
  | { type: "sub"; icon: string | null; title: string }
  | { type: "item"; title: string | null; text: string }
  | { type: "tip"; text: string };

export type SectionId =
  | "portrait" | "core" | "love" | "perception" | "reactions" | "strengths" | "blindspots"
  | "conflict" | "challenges" | "growth" | "relationships" | "career" | "journey" | "advice";

export type Section = { id: SectionId; title: string; blocks: Block[] };

export type Report = {
  slug: string;
  code: string;
  english: string;
  name: string;
  intro: string[];
  population: number | null;
  celebrities: { name: string; text: string }[];
  powers: { title: string | null; english: string | null; lead: string | null; points: { title: string; text: string }[] }[];
  sections: Section[];
};

const REPORTS = { caregiver, creator, everyman, explorer, hero, innocent, jester, lover, magician, rebel, ruler, sage } as unknown as Record<string, Report>;

export function getReport(slug: string): Report | null {
  return REPORTS[slug] ?? null;
}

export function getSection(report: Report, id: SectionId): Section {
  return report.sections.find((s) => s.id === id) ?? { id, title: "", blocks: [] };
}

/** Splits a section into its lead paragraphs and the groups that follow each sub-heading. */
export function groupBlocks(blocks: Block[]) {
  const lead: Block[] = [];
  const groups: { sub: Extract<Block, { type: "sub" }>; blocks: Block[] }[] = [];
  for (const b of blocks) {
    if (b.type === "sub") groups.push({ sub: b, blocks: [] });
    else if (groups.length) groups.at(-1)!.blocks.push(b);
    else lead.push(b);
  }
  return { lead, groups };
}

export const IMAGE_NAMES = ["hero", "portrait", "core", "love", "symbol"] as const;
export type ImageName = (typeof IMAGE_NAMES)[number];
export type ReportImages = Record<ImageName, string | null>;

const EXTENSIONS = ["webp", "png", "jpg", "jpeg", "avif"];

/** Finds generated images in public/images/report/<slug>/ (prompts: docs/image-prompts/). */
export function getReportImages(slug: string): ReportImages {
  const dir = path.join(process.cwd(), "public", "images", "report", slug);
  const found = {} as ReportImages;
  for (const name of IMAGE_NAMES) {
    const ext = EXTENSIONS.find((e) => fs.existsSync(path.join(dir, `${name}.${e}`)));
    found[name] = ext ? `/images/report/${slug}/${name}.${ext}` : null;
  }
  return found;
}
